"""Write model_repository/<name>/config.pbtxt and labels from build/<name>/meta.json.

The tensor names, types and shapes come from the exported graph (meta.json),
never from a template. Input is the UINT8 NHWC tensor added by wrap_uint8.py, or
for sequence models the FP32 feature window recorded in meta["input"]. Every
graph output is declared (segmentation has two: detections and mask prototypes).

    python export/gen_config.py [--only name ...]
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

DTYPES = {"UINT8": "TYPE_UINT8", "FLOAT": "TYPE_FP32", "FLOAT16": "TYPE_FP16", "INT32": "TYPE_INT32", "INT64": "TYPE_INT64"}

TEMPLATE = """\
# Generated by inference/export/gen_config.py from build/{name}/meta.json. Do not edit by hand.
name: "{name}"
platform: "tensorrt_plan"
max_batch_size: {max_batch}

input [
  {{
    name: "{in_name}"
    data_type: {in_type}
    dims: [ {in_dims} ]
  }}
]

output [
{outputs}
]

dynamic_batching {{
  preferred_batch_size: [ {preferred} ]
  max_queue_delay_microseconds: {queue_delay_us}
  default_queue_policy {{
    max_queue_size: {max_queue}
    timeout_action: REJECT
    default_timeout_microseconds: {timeout_us}
    allow_timeout_override: true
  }}
}}

instance_group [
  {{
    count: {instances}
    kind: KIND_GPU
    gpus: [ 0 ]
  }}
]

# The registry serves each version as its own Triton model (<name>__v<version>),
# generated from this file; see api/app/services/model_registry.py.
version_policy: {{ latest: {{ num_versions: 1 }} }}

model_warmup [
  {{
    name: "zeros"
    batch_size: {warm_batch}
    inputs {{
      key: "{in_name}"
      value: {{
        data_type: {in_type}
        dims: [ {in_dims} ]
        zero_data: true
      }}
    }}
  }}
]

parameters {{ key: "task" value: {{ string_value: "{task}" }} }}
"""


LABELLED = ("classify", "sequence")


def input_spec(meta: dict) -> dict:
    """The served engine's input (older meta.json files predate the ``input`` key: images)."""
    return meta.get("input") or {"name": "images", "dtype": "UINT8", "dims": [meta["imgsz"], meta["imgsz"], 3]}


def render(meta: dict, queue_delay_us: int = 3000, max_queue: int = 256, timeout_us: int = 500_000) -> str:
    inp = input_spec(meta)
    outputs = []
    for i, out in enumerate(meta["onnx_outputs"]):
        label = '\n    label_filename: "labels.txt"' if meta["task"] in LABELLED and i == 0 else ""
        dims = ", ".join(str(d) for d in out["shape"][1:])
        outputs.append('  {\n    name: "%s"\n    data_type: %s\n    dims: [ %s ]%s\n  }'
                       % (out["name"], DTYPES[out["dtype"]], dims, label))
    maxb = meta["max_batch"]
    preferred = ", ".join(str(b) for b in (4, 8, 16, 32) if b <= maxb)
    return TEMPLATE.format(
        name=meta["name"], max_batch=maxb, in_name=inp["name"], in_type=DTYPES[inp["dtype"]],
        in_dims=", ".join(str(d) for d in inp["dims"]), outputs=",\n".join(outputs),
        preferred=preferred, queue_delay_us=queue_delay_us, max_queue=max_queue, timeout_us=timeout_us,
        warm_batch=meta["opt_batch"], task=meta["task"], instances=meta.get("instances", 1),
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", nargs="*")
    args = parser.parse_args()
    for meta_path in sorted((ROOT / "build").glob("*/meta.json")):
        meta = json.loads(meta_path.read_text())
        if args.only and meta["name"] not in args.only:
            continue
        repo = ROOT / "model_repository" / meta["name"]
        repo.mkdir(parents=True, exist_ok=True)
        (repo / "config.pbtxt").write_text(render(meta))
        names = [meta["names"][str(i)] for i in range(meta["num_classes"])]
        (repo / "labels.txt").write_text("\n".join(names) + "\n")
        # The API reads this to know the task, class names and letterbox size.
        (repo / "model_meta.json").write_text(json.dumps(
            {**{k: meta[k] for k in ("name", "task", "imgsz", "max_batch", "num_classes", "names", "weights",
                                     "architecture", "embedded_nms", "end2end")},
             "input": input_spec(meta),
             "precision": meta.get("precision", "fp16"),
             "framework": "pytorch" if meta["task"] == "sequence" else "ultralytics",
             "outputs": [{"name": o["name"], "shape": o["shape"][1:]} for o in meta["onnx_outputs"]],
             **{k: meta[k] for k in ("kpt_shape", "num_masks") if k in meta}}, indent=2))
        print(f"wrote {repo}/config.pbtxt")


if __name__ == "__main__":
    main()
